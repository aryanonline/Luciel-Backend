"""POST /api/v1/webhooks/stripe — Stripe webhook receiver (Architecture §3.4.1b).

Verify-before-route (HARD CONSTRAINT #4, Arc 13 discipline): the raw body + the
``Stripe-Signature`` header are verified by the gateway BEFORE the event is parsed
or acted on. An unverified/garbled signature → 400 reject, nothing processed.

Tenant resolution: the webhook arrives with no session cookie. The primary key is
the verified event's ``customer`` id matched against ``billing_accounts
.stripe_customer_id`` — the binding we wrote ourselves; ``metadata.admin_id`` is the
fallback for objects we created and tagged. We then open a ``tenant_session(admin_id)``
so RLS scopes every mutation; without the GUC, tenant tables are invisible (safe
default).

Idempotent (HARD CONSTRAINT, §3.4.1b): a redelivered event id is a no-op, gated on
the ``processed_stripe_events`` primary key.
"""

from __future__ import annotations

import logging
import uuid

from fastapi import APIRouter, Depends, Request
from sqlalchemy import text

from app.api.errors import validation_error
from app.billing import webhooks as billing_webhooks
from app.billing.stripe_gateway import (
    SignatureError,
    StripeEvent,
    StripeGateway,
    get_stripe_gateway,
)
from app.config import get_settings
from app.db.session import tenant_session, untenanted_session

router = APIRouter(prefix="/api/v1/webhooks", tags=["webhooks"])
_log = logging.getLogger(__name__)


def _metadata_admin_id(event: StripeEvent) -> uuid.UUID | None:
    metadata = event.data.get("metadata")
    if not isinstance(metadata, dict):
        return None
    try:
        return uuid.UUID(str(metadata.get("admin_id")))
    except (ValueError, TypeError):
        return None


async def _resolve_tenant(event: StripeEvent) -> uuid.UUID | None:
    """Which tenant this verified event belongs to (§3.4.1b, P1-11).

    ``metadata.admin_id`` alone was not enough: Stripe carries metadata only on objects
    we tagged, and the events that actually drive billing state — invoice.paid,
    invoice.payment_failed, payment_method.detached — are generated by Stripe and arrive
    without it. Every one of them does carry ``customer``, which is the binding we stored
    on the billing account. Without this the counter never reset and dunning never
    started, and the route returned 200 so Stripe never retried.

    The lookup is cross-tenant and runs before any GUC is set, so it goes through the
    SECURITY DEFINER seam (migration 0024) that returns the tenant id and nothing else.
    """
    customer = event.data.get("customer")
    if isinstance(customer, str) and customer:
        async with untenanted_session() as s:
            row = (
                await s.execute(
                    text("SELECT admin_id FROM billing_tenant_for_stripe_customer(:cid)"),
                    {"cid": customer},
                )
            ).first()
        if row is not None:
            return uuid.UUID(str(row[0]))
    return _metadata_admin_id(event)


@router.post("/stripe")
async def stripe_webhook(
    request: Request,
    gateway: StripeGateway = Depends(get_stripe_gateway),
) -> dict[str, str]:
    raw = await request.body()
    signature = request.headers.get("Stripe-Signature", "")

    # Verify FIRST (HARD CONSTRAINT #4). Unverified → reject, act on nothing.
    try:
        event = gateway.verify_and_parse(payload=raw, signature_header=signature)
    except SignatureError as exc:
        # 422 maps to validation_error on the frontend; for a server-to-server
        # webhook the body is non-customer-facing. Reject without processing.
        raise validation_error("Invalid Stripe signature.") from exc

    if get_settings().stripe_integration_posture == "mock":
        # Round 7 WP-1 #5: billing is NOT live in this posture — the gateway is the
        # in-process fake and nothing this deployment shows as "saved" or "billed" came
        # from Stripe. A verified event still mutates nothing here: a real whsec_ in a
        # mock-posture production would otherwise let Stripe's account state (or a
        # replay of it) flip billing state the deployment cannot honour. 200 so Stripe
        # stops retrying; logged so the operator can see events reaching a deployment
        # that ignores them; nothing claimed, so the posture flip processes a redelivery.
        _log.warning(
            "stripe webhook ignored: stripe_integration_posture=mock event_id=%s type=%s",
            event.event_id,
            event.type,
        )
        return {"status": "ignored", "reason": "mock_posture"}

    admin_id = await _resolve_tenant(event)
    if admin_id is None:
        return {"status": "ignored", "reason": "unknown_tenant"}

    async with tenant_session(admin_id) as s:
        action = await billing_webhooks.handle_event(s, admin_id=admin_id, event=event)
    return {"status": "ok", "action": action}
